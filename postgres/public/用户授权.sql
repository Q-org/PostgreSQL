--1 创建用户wei（已存在就注释掉）
CREATE ROLE wei
LOGIN
PASSWORD 'wei';

--2 允许连接postgres数据库
GRANT CONNECT ON DATABASE postgres TO wei;

--3 schema使用权限 public
GRANT USAGE ON SCHEMA public TO wei;

--4 现有表：增删改查
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO wei;

--5 序列权限（自增主键）
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO wei;

--6 函数授权（ROUTINES = FUNCTION + PROCEDURE，PG12+推荐）
GRANT EXECUTE ON ALL ROUTINES IN SCHEMA public TO wei;

--7 默认权限：以后新建的表/序列/函数自动授权给wei
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT,INSERT,UPDATE,DELETE ON TABLES TO wei;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT USAGE,SELECT ON SEQUENCES TO wei;

-- ROUTINES 包含函数+存储过程，作为新建routine默认权限
ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT EXECUTE ON ROUTINES TO wei;
